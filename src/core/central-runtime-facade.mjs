export function createCentralRuntimeFacade(deps = {}) {
  const {
    win = globalThis,
    documentRef = globalThis.document,
    navigatorRef = globalThis.navigator,
    storageConstructor = globalThis.Storage,
    blobConstructor = globalThis.Blob,
    urlApi = globalThis.URL,
    ui = {},
    storageKeys = {},
    formatDataSafetyTime = (value) => String(value || ""),
    getActiveWorkspaceId = () => "",
    getCurrentPlatformUser = () => null,
    handleSyncStatus = () => {},
    handleSyncedStateValue = () => {},
    isSessionPlannerAutosaveKey = () => false,
    mergeDashboardPresentationStatePreservingLocalEdits = (_currentValue, syncedValue) => syncedValue,
    mergePeriodizationStatePreservingLocalUi = (_currentValue, syncedValue) => syncedValue,
    mergeScheduleStatePreservingLocalUi = (_currentValue, syncedValue) => syncedValue,
    getSessionPlannerLocalUiState = () => null,
    setAutosaveStatusForKey = () => {},
    shouldDeferCentralizedAppStateReload = () => false,
    showSessionPlannerToast = () => {},
  } = deps;

  let centralSyncRuntimeService = null;
  const dataSafetyStorageConfig = createCentralRuntimeStorageConfig(storageKeys);
  const dataSafetyRuntimeService = createDataSafetyRuntimeService({
    win,
    documentRef,
    navigatorRef,
    storageConstructor,
    blobConstructor,
    urlApi,
    ui,
    storageKey: storageKeys.dataSafetyStorageKey || "football-data-safety-v1",
    exportSchema: storageKeys.dataSafetyExportSchema || "football-science-backup-v1",
    databaseName: storageKeys.dataSafetyDatabaseName || "football-science-data-safety-v1",
    snapshotStoreName: dataSafetySnapshotStoreName,
    latestStoreName: dataSafetyLatestStoreName,
    maxSnapshots: dataSafetyMaxSnapshots,
    protectedStorageKeys: dataSafetyStorageConfig.protectedStorageKeys,
    storageLabels: dataSafetyStorageConfig.storageLabels,
    legacyStorageKeys: dataSafetyStorageConfig.legacyStorageKeys,
    formatDataSafetyTime,
    canWriteCentralBackedCache: () => centralSyncRuntimeService?.canWriteCentralBackedCache?.() ?? true,
    createCentralBackedStorageError: () => centralSyncRuntimeService?.createCentralBackedStorageError?.() ?? new Error("Central sync is not ready."),
    getCentralStateBridge: () => centralSyncRuntimeService?.getCentralStateBridge?.() ?? null,
    getCentralStateWriteSuppressionKeys: () => centralSyncRuntimeService?.centralStateWriteSuppressionKeys ?? new Set(),
    queueCentralStateWrite: (...args) => centralSyncRuntimeService?.queueCentralStateWrite?.(...args),
  });

  centralSyncRuntimeService = createCentralSyncRuntimeService({
    getActiveWorkspaceId,
    getCurrentUser: getCurrentPlatformUser,
    getDataSafetyNow: dataSafetyRuntimeService.getNow,
    getStorageLabel: dataSafetyRuntimeService.getStorageLabel,
    handleSyncedStateValue,
    handleSyncStatus,
    hashString: dataSafetyRuntimeService.hashString,
    isProtectedStorageKey: dataSafetyRuntimeService.isProtectedStorageKey,
    isSessionPlannerAutosaveKey,
    isCentralStateTransitionFenceActive: () => dataSafetyRuntimeService.isCentralStateTransitionFenceActive?.() === true,
    mergeDashboardPresentationStatePreservingLocalEdits,
    mergePeriodizationStatePreservingLocalUi,
    mergeScheduleStatePreservingLocalUi,
    mutateManifest: dataSafetyRuntimeService.mutateManifest,
    mutateManifestWithResult: dataSafetyRuntimeService.mutateManifestWithResult,
    periodizationStorageKey: storageKeys.periodizationStorageKey,
    queueSnapshot: dataSafetyRuntimeService.queueSnapshot,
    queueStatusRefresh: dataSafetyRuntimeService.queueStatusRefresh,
    readManifest: dataSafetyRuntimeService.readManifest,
    rawGetItem: dataSafetyRuntimeService.rawGetItem,
    rawSetItem: dataSafetyRuntimeService.rawSetItem,
    retryConflictStorageKeys: [storageKeys.dashboardPresentationStorageKey].filter(Boolean),
    dashboardPresentationStorageKey: storageKeys.dashboardPresentationStorageKey,
    scheduleStorageKey: storageKeys.scheduleStorageKey,
    getSessionPlannerLocalUiState,
    sessionPlannerStorageKey: storageKeys.sessionPlannerStorageKey,
    setAutosaveStatusForKey,
    shouldDeferReload: shouldDeferCentralizedAppStateReload,
    showSessionPlannerToast,
    win,
  });

  return {
    dataSafetyRuntimeStatus: dataSafetyRuntimeService.status,
    centralStateWriteSuppressionKeys: centralSyncRuntimeService.centralStateWriteSuppressionKeys,
    getDataSafetyNow: (...args) => dataSafetyRuntimeService.getNow(...args),
    isDataSafetyInternalStorageKey: (...args) => dataSafetyRuntimeService.isInternalStorageKey(...args),
    isDataSafetyProtectedStorageKey: (...args) => dataSafetyRuntimeService.isProtectedStorageKey(...args),
    rawDataSafetyGetItem: (...args) => dataSafetyRuntimeService.rawGetItem(...args),
    rawDataSafetySetItem: (...args) => dataSafetyRuntimeService.rawSetItem(...args),
    rawDataSafetyRemoveItem: (...args) => dataSafetyRuntimeService.rawRemoveItem(...args),
    readDataSafetyManifest: (...args) => dataSafetyRuntimeService.readManifest(...args),
    mutateDataSafetyManifest: (...args) => dataSafetyRuntimeService.mutateManifest(...args),
    hashDataSafetyString: (...args) => dataSafetyRuntimeService.hashString(...args),
    getDataSafetyStorageLabel: (...args) => dataSafetyRuntimeService.getStorageLabel(...args),
    recordDataSafetyWrite: (...args) => dataSafetyRuntimeService.recordWrite(...args),
    saveDataSafetySnapshot: (...args) => dataSafetyRuntimeService.saveSnapshot(...args),
    queueDataSafetySnapshot: (...args) => dataSafetyRuntimeService.queueSnapshot(...args),
    refreshDataSafetyStatus: (...args) => dataSafetyRuntimeService.refreshStatus(...args),
    queueDataSafetyStatusRefresh: (...args) => dataSafetyRuntimeService.queueStatusRefresh(...args),
    exportFootballScienceDataBackup: (...args) => dataSafetyRuntimeService.exportBackup(...args),
    importFootballScienceDataBackupFile: (...args) => dataSafetyRuntimeService.importBackupFile(...args),
    openDataSafetyDatabase: (...args) => dataSafetyRuntimeService.openDatabase(...args),
    flushQueuedDataSafetySnapshot: (...args) => dataSafetyRuntimeService.flushQueuedSnapshot(...args),
    installFootballDataSafety: (...args) => dataSafetyRuntimeService.install(...args),
    getCentralStateBridge: (...args) => centralSyncRuntimeService.getCentralStateBridge(...args),
    getCentralStateMetadataForKey: (...args) => centralSyncRuntimeService.getCentralStateMetadataForKey(...args),
    getCentralStateRevisionForKey: (...args) => centralSyncRuntimeService.getCentralStateRevisionForKey(...args),
    canWriteCentralBackedCache: (...args) => centralSyncRuntimeService.canWriteCentralBackedCache(...args),
    createCentralBackedStorageError: (...args) => centralSyncRuntimeService.createCentralBackedStorageError(...args),
    queueCentralStateStatus: (...args) => centralSyncRuntimeService.queueCentralStateStatus(...args),
    hasPendingCentralStateWrites: () => centralSyncRuntimeService.hasPendingCentralStateWrites(dataSafetyRuntimeService.readManifest),
    retryCentral: () => centralSyncRuntimeService.retryCentral(dataSafetyRuntimeService.readManifest),
    applyCentralSyncedStateValue: (...args) => centralSyncRuntimeService.applyCentralSyncedStateValue(...args),
    getCentralSyncResultValue: (...args) => centralSyncRuntimeService.getCentralSyncResultValue(...args),
    getCentralSyncResultRevision: (...args) => centralSyncRuntimeService.getCentralSyncResultRevision(...args),
    retryCentralStateWriteAfterConflict: (...args) => centralSyncRuntimeService.retryCentralStateWriteAfterConflict(...args),
    registerSessionPlannerCentralSyncConflict: (...args) => centralSyncRuntimeService.registerSessionPlannerCentralSyncConflict(...args),
    queueCentralStateWrite: (...args) => centralSyncRuntimeService.queueCentralStateWrite(...args),
    flushCentralStateWrites: (...args) => centralSyncRuntimeService.flushCentralStateWrites(...args),
    clearCentralStateWriteTimer: (...args) => centralSyncRuntimeService.clearCentralStateWriteTimer(...args),
  };
}
