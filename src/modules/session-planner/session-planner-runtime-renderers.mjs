    isTacticalEndpointElement: deps.isSessionPlannerTacticalEndpointElement,
    getTacticalPitchDimensionsForBlock: deps.getSessionPlannerTacticalPitchDimensionsForBlock,
    cloneTacticalElement: deps.cloneSessionPlannerTacticalElement,
    createLineElement: deps.createSessionPlannerLineElement,
    renderSelectionBox: deps.renderSessionPlannerTacticalSelectionBox,
    ensureTacticalFrames: deps.ensureSessionPlannerTacticalFrames,
    getTacticalActiveFrameId: deps.getSessionPlannerTacticalActiveFrameId,
    getTacticalSelectedElementIds: deps.getSessionPlannerTacticalSelectedElementIds,
