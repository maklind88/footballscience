export function createExerciseLibraryRuntimeFacade(options = {}) {
  const getRuntime = typeof options.getRuntime === "function" ? options.getRuntime : () => null;
  const callRuntime = (methodName, args) => {
    const method = getRuntime()?.[methodName];
    if (typeof method !== "function") throw new Error(`Exercise Library runtime is missing method: ${methodName}`);
    return method(...args);
  };

  return Object.fromEntries(
    exerciseLibraryRuntimeMethodNames.map((methodName) => [
      methodName,
      (...args) => callRuntime(methodName, args),
    ])
  );
}
