    clamp: deps.clamp,
    comparePlayers: deps.compareMedicalPlayers,
    getBridgeBestMatches: deps.getSessionPlannerPlayerBoardBridgeBestMatches,
    getCareerScore: getSessionPlannerPlayerBoardCareerScore,
