export function createMedicalRtpLibraryStarterDraft(profileId = "", playerId = "", selectedDate = "") {
  const selectedProfile = getMedicalRtpLibraryProfileById(profileId);
  const starter = selectedProfile?.starter;
  const cleanPlayerId = String(playerId || "").trim();
  if (!selectedProfile || !starter || !cleanPlayerId) {
    return null;
  }
  const section = (title, items = []) => `${title}: ${items.join("; ")}`;
  return {
    playerId: cleanPlayerId,
    injuryType: selectedProfile.name,
    bodyArea: selectedProfile.bodyArea,
    startDate: selectedDate,
    duration: starter.duration,
    durationUnit: starter.unit,
    status: starter.status,
    rtpPhase: starter.rtpPhase,
    participation: starter.participation,
    reviewDate: "",
    phase: `RTP Library starter - ${selectedProfile.name}`,
    comment: [
      `RTP Library guide: ${selectedProfile.name}`,
      `Quick summary: ${selectedProfile.summary}`,
      section("RTP phases", selectedProfile.phases),
      section("Movement/load", selectedProfile.loadText),
      section("Risk factors", selectedProfile.riskTags),
      section("Warning points", selectedProfile.redFlags),
      section("Gate criteria", selectedProfile.criteria),
      section("Next step", selectedProfile.trainingChecklist),
      section("Hold rules", selectedProfile.redFlags),
      `Evidence level: ${selectedProfile.evidenceLevel}`,
      `Evidence: ${selectedProfile.evidence}`,
      `Experience/consensus: ${selectedProfile.experience}`,
    ].join("\n"),
    coachNote: starter.coachNote,
    shareWithCoach: false,
    rtpLibraryProfileId: selectedProfile.id,
    rtpLibraryProfileName: selectedProfile.name,
    rtpLibraryEvidenceLevel: selectedProfile.evidenceLevel,
    rtpLibrarySummary: selectedProfile.summary,
    rtpProgramPhases: selectedProfile.phases,
    rtpProgramLoadText: selectedProfile.loadText,
    rtpProgramRiskFactors: selectedProfile.riskTags,
    rtpProgramWarningPoints: selectedProfile.redFlags,
    rtpProgramGateCriteria: selectedProfile.criteria,
    rtpProgramNextSteps: selectedProfile.trainingChecklist,
    rtpProgramHoldRules: selectedProfile.redFlags,
  };
}
