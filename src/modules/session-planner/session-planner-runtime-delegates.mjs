export function createSessionPlannerRuntimeDelegates({ getController } = {}) {
  if (typeof getController !== "function") {
    throw new TypeError("Session planner runtime delegates require getController.");
  }
  return Object.fromEntries(sessionPlannerRuntimeDelegateMethodNames.map((methodName) => [
    methodName,
    (...args) => {
      const controller = getController();
      const method = controller?.[methodName];
      if (typeof method !== "function") {
        throw new TypeError(`Session planner workspace controller is missing ${methodName}.`);
      }
      return method.apply(controller, args);
    },
  ]));
}
